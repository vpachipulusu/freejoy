"""From a validated Awin promotion to the rows the catalogue stores, and the fingerprint of an edit.

What an import writes, and what it deliberately does not:

* The offer is always a ``DRAFT``, never featured, never verified (``last_verified_at`` stays null, so
  ``publish_blockers`` reports ``not_verified``), with no freshness label.
* ``voucher`` and ``promotion`` both map to ``VOUCHER``, the closest existing type. Nothing is ever
  ``FREE_SAMPLE``. An editor changes the type if the offer is something else.
* Postage is ``CHECK_TERMS`` and ``requires_card`` stays false: nothing is claimed that the feed does
  not say. ``eligibility`` is the promotion's terms (or a neutral line that sends the reader to them).
* Voucher codes are not stored (the model has no field and free text would hide the code from
  review). ``publisher_notes`` (internal, never serialised by the public API) says that one exists.
* The category is the disabled "Imported (uncategorised)" one, so ``category_disabled`` blocks
  publishing until an editor chooses a real category.
* The merchant is created inactive, so ``merchant_inactive`` blocks publishing until an editor
  activates it. Its website is the origin of the promotion's own ``url``, never a tracking host.

``fingerprint`` hashes every field an editor can change on an offer, its status and verification
date, and its affiliate links (provider, destination, tracking id, active), and nothing else (not ids,
slugs or timestamps). The importer stores it each time it writes an offer; a later mismatch means a
person changed the offer, so it is no longer an untouched import.
"""

import hashlib
import json
from collections.abc import Mapping, Sequence
from datetime import UTC, datetime
from typing import Any
from urllib.parse import urlsplit

from app.core.affiliate_hosts import host_matches
from app.core.plain_text import plain_line
from app.core.slugs import CATALOGUE_SLUG_MAX_LENGTH, InvalidSlug, slugify
from app.models.platform.offer import OfferStatus, OfferType, PostageKind
from app.repositories.admin_offers import AffiliateLinkRecord, OfferRecord
from app.repositories.awin_import import IMPORT_CATEGORY_SLUG
from app.services.awin_promotions import (
    NETWORK_HOSTS,
    PROVIDER,
    Promotion,
)
from app.services.offer_rules import EDITABLE_FIELDS

IMAGE_TINT = "cream"
IMAGE_ALT = "Illustration of a voucher ticket"
IMAGE_LABEL_LENGTH = 40
DEFAULT_ELIGIBILITY = "See the offer terms on the merchant's site before you claim."
AVAILABILITY = (
    "Listed for UK customers. Check the merchant's terms for dates and exclusions."
)
FINGERPRINT_VERSION = (
    1  # bump with FINGERPRINT_FIELDS: stored fingerprints then stop matching, safely
)
FINGERPRINT_FIELDS = tuple(sorted(EDITABLE_FIELDS | {"status", "last_verified_at"}))
REFRESH_FIELDS = (
    "title",
    "summary",
    "description",
    "offer_type",
    "source_url",
    "start_at",
    "end_at",
    "eligibility",
    "publisher_notes",
)


def _notes(promotion: Promotion) -> str:
    notes = f"Imported from Awin (promotion {promotion.promotion_id}). Review every field before publishing."
    if promotion.has_voucher_code:
        notes += " Awin lists a voucher code for this promotion; the importer does not store codes."
    return notes


def refresh_values(promotion: Promotion) -> dict[str, Any]:
    """The fields a refresh of an untouched import rewrites (nothing an editor would have chosen)."""
    return {
        "title": promotion.title,
        "summary": promotion.summary,
        "description": list(promotion.description),
        "offer_type": OfferType.VOUCHER,
        "source_url": promotion.source_url,
        "start_at": promotion.start_at,
        "end_at": promotion.end_at,
        "eligibility": promotion.terms or DEFAULT_ELIGIBILITY,
        "publisher_notes": _notes(promotion),
    }


def offer_values(
    promotion: Promotion, category_id: str, merchant_id: str, slug: str
) -> dict[str, Any]:
    """Every column of a new draft offer (the id is generated by the model)."""
    return {
        **refresh_values(promotion),
        "slug": slug,
        "category_id": category_id,
        "merchant_id": merchant_id,
        "status": OfferStatus.DRAFT,
        "featured": False,
        "image_tint": IMAGE_TINT,
        "image_label": plain_line(promotion.advertiser_name, IMAGE_LABEL_LENGTH),
        "image_alt": IMAGE_ALT,
        "postage_kind": PostageKind.CHECK_TERMS,
        "postage_amount_minor": None,
        "postage_currency": None,
        "requires_card": False,
        "subscription_terms": None,
        "availability": AVAILABILITY,
        "steps": [],
        "last_verified_at": None,
        "freshness": None,
    }


def link_values(promotion: Promotion) -> dict[str, Any]:
    return {
        "provider": PROVIDER,
        "destination_url": promotion.tracking_url,
        "tracking_id": None,
        "active": True,
    }


def merchant_website(promotion: Promotion) -> str | None:
    """The origin of the promotion's own URL, or ``None`` (no URL, or one on a network's host)."""
    if promotion.source_url is None:
        return None
    host = urlsplit(promotion.source_url).hostname
    if not host or host_matches(host, NETWORK_HOSTS):
        return None
    return f"https://{host}"


def merchant_values(promotion: Promotion, slug: str) -> dict[str, Any]:
    return {
        "name": promotion.advertiser_name,
        "slug": slug,
        "website": merchant_website(promotion),
        "logo_url": None,
        "active": False,
    }


def import_category_values() -> dict[str, Any]:
    """The disabled holding category for imports. ``enabled`` is false for good: see the docs."""
    return {
        "name": "Imported (uncategorised)",
        "slug": IMPORT_CATEGORY_SLUG,
        "short_name": "Imported",
        "description": "Imported offers waiting for an editor to choose a category.",
        "intro": "Imported offers waiting for an editor to choose a category.",
        "tint": IMAGE_TINT,
        "sort_order": 9999,
        "enabled": False,
    }


def _slug_with_suffix(text: str, suffix: str) -> str | None:
    try:
        base = slugify(text, CATALOGUE_SLUG_MAX_LENGTH - len(suffix) - 1)
    except InvalidSlug:
        return None
    return f"{base}-{suffix}"


def offer_slug_candidates(promotion: Promotion) -> tuple[str, ...]:
    """Slugs to try in order: the title plus the promotion id, then ``awin-<id>``. All end in the id."""
    suffix = str(promotion.promotion_id)
    fallback = f"{PROVIDER}-{suffix}"
    titled = _slug_with_suffix(promotion.title, suffix)
    return (titled, fallback) if titled else (fallback,)


def merchant_slug_candidates(promotion: Promotion) -> tuple[str, ...]:
    """The advertiser name, then the name plus the advertiser id, then ``awin-advertiser-<id>``."""
    suffix = str(promotion.advertiser_id)
    fallback = f"{PROVIDER}-advertiser-{suffix}"
    try:
        plain = slugify(promotion.advertiser_name)
    except InvalidSlug:
        return (fallback,)
    with_id = _slug_with_suffix(promotion.advertiser_name, suffix)
    return tuple(dict.fromkeys(s for s in (plain, with_id, fallback) if s))


def _canonical(value: Any) -> Any:
    if isinstance(value, datetime):
        return value.astimezone(UTC).isoformat()
    raise TypeError(f"unexpected {type(value).__name__} in a fingerprint")


def fingerprint(offer: OfferRecord, links: Sequence[AffiliateLinkRecord]) -> str:
    """SHA-256 (hex) of the offer's editable state and its links, as an editor would see them."""
    state: Mapping[str, Any] = {
        "v": FINGERPRINT_VERSION,
        "offer": {name: getattr(offer, name) for name in FINGERPRINT_FIELDS},
        "links": sorted(
            (
                [link.provider, link.destination_url, link.tracking_id, link.active]
                for link in links
            ),
            key=repr,
        ),
    }
    payload = json.dumps(
        state, sort_keys=True, separators=(",", ":"), default=_canonical
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()
